    rows.append(f"{tn} & {MODELS_BY_NAME[tn].k} & "
                + " & ".join(f"{100*np.mean([r[k] for r in s]):.1f}"
                             for k in ("recovery_r2", "recovery_r2_adj",
                                       "recovery_aicc", "recovery_bic")) + r" \\")
