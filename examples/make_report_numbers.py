OUT = os.path.join(ROOT, "paper", "numbers.tex")
lines = []


def cmd(name, value):
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def _write_table(path, header_tex, rows, caption, label, colspec):
    """Write a complete table environment.

    The body cannot be \\input inside a tabular: LaTeX's \\input opens a
    group that TeX's alignment scanner rejects, so \\bottomrule then lands
    inside a half started row. Emitting the whole float sidesteps it.
    """
    body = "\n".join(rows)
    with open(path, "w") as fh:
        fh.write("% generated by examples/make_report_numbers.py\n")
        fh.write("\\begin{table}[t]\n\\centering\n\\small\n")
        fh.write(f"\\caption{{{caption}}}\n\\label{{{label}}}\n")
        fh.write(f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n")
        fh.write(header_tex + "\n\\midrule\n")
        fh.write(body + "\n\\bottomrule\n")
        fh.write("\\end{tabular}\n\\end{table}\n")


def pct(x, d=0):
    return f"{100*x:.{d}f}\\%"


