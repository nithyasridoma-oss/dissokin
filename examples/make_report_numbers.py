cmd("InteriorNs", ", ".join(f"{v:.2f}" for v in sorted({r["n_true"] for r in inter})))
cmd("BoundaryNs", ", ".join(f"{v:.2f}" for v in sorted({r["n_true"] for r in bound})))
for npf in sorted({r["n_points_full"] for r in Rm}):
    sub = [r for r in Rm if r["n_points_full"] == npf]
    cmd(f"Cov{'Six' if npf==6 else 'Eight' if npf==8 else 'Twelve'}",
        pct(np.mean([r["ci_coverage"] for r in sub])))
    cmd(f"Kept{'Six' if npf==6 else 'Eight' if npf==8 else 'Twelve'}",
        f"{np.mean([r['mean_points_kept'] for r in sub]):.1f}")
