cmd("RecAICcOnePar", pct(np.mean([r["recovery_aicc"] for r in one_par])))
cmd("RecRtwoTwoPar", pct(np.mean([r["recovery_r2"] for r in two_par])))
cmd("RecAICcTwoPar", pct(np.mean([r["recovery_aicc"] for r in two_par])))
cmd("NOnePar", f"{len(one_par) * S['n_rep']:,}".replace(",", "\\,"))

def top_pick(truth, field):
    c = Counter()
    for r in R:
        if r["truth"] == truth:
            c.update(r[field])
    tot = sum(c.values())
    m, n = c.most_common(1)[0]
    return m, n / tot

m, f = top_pick("Higuchi", "picks_r2");  cmd("HigPickRtwo", m); cmd("HigPickRtwoF", pct(f))
m, f = top_pick("Higuchi", "picks_aicc"); cmd("HigPickAICcF", pct(f))
m, f = top_pick("First order", "picks_r2"); cmd("FoPickRtwo", m); cmd("FoPickRtwoF", pct(f))
m, f = top_pick("Korsmeyer-Peppas", "picks_aicc")
cmd("KPPickAICc", m); cmd("KPPickAICcF", pct(f))
cmd("KPRecAICc", pct(np.mean([r["recovery_aicc"] for r in R
                              if r["truth"] == "Korsmeyer-Peppas"])))
cmd("KPRecRtwo", pct(np.mean([r["recovery_r2"] for r in R
                              if r["truth"] == "Korsmeyer-Peppas"])))
lo = [r for r in R if r["sigma"] == 1.0]
hi = [r for r in R if r["sigma"] == 5.0]
cmd("RecAICcLowNoise", pct(np.mean([r["recovery_aicc"] for r in lo])))
cmd("RecAICcHighNoise", pct(np.mean([r["recovery_aicc"] for r in hi])))
six = [r for r in R if r["n_points"] == 6]
sixteen = [r for r in R if r["n_points"] == 16]
cmd("RecAICcSix", pct(np.mean([r["recovery_aicc"] for r in six])))
cmd("RecAICcSixteen", pct(np.mean([r["recovery_aicc"] for r in sixteen])))

# per truth table
rows = []
